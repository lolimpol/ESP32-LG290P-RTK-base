#pragma once
// RTCM 3.x framing helpers. No Arduino dependencies (host-testable).
#include <stdint.h>
#include <stddef.h>

namespace Rtcm {

// Frame: D3 | 000000 LL | LL | payload[len] | CRC24Q[3]
const uint16_t MAX_PAYLOAD = 1023;
const uint16_t MAX_FRAME   = MAX_PAYLOAD + 6;

// CRC-24Q: poly 0x1864CFB, init 0, MSB first, no xor-out.  Check("123456789") = 0xCDE703.
uint32_t crc24q(const uint8_t* d, size_t n);

// DF002 message number = first 12 bits of payload. Requires payload length >= 2.
inline uint16_t msgNumber(const uint8_t* frame) {
  return (uint16_t)(((uint16_t)frame[3] << 4) | (frame[4] >> 4));
}

// Catalogue of messages the UI can select. Index == bit in AppConfig::rtcmMask.
// Index 0 (1005) is special: it is *generated by the ESP32*, never taken from the receiver.
struct CatalogEntry { uint16_t num; const char* name; };
extern const CatalogEntry kCatalog[];
extern const uint8_t kCatalogCount;
const uint8_t IDX_1005 = 0;
int catalogIndex(uint16_t num);   // -1 if not in catalogue

}  // namespace Rtcm
