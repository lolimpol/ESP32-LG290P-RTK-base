#!/usr/bin/env python3
"""Gzip data/{index.html,style.css,app.js} and emit src/WebAssets.h (byte arrays in flash).
Runs automatically before every PlatformIO build (see platformio.ini); Arduino IDE users run it manually
after editing the web files:  python3 tools/embed_web.py"""
import gzip, os, sys

try:                                   # PlatformIO/SCons context: __file__ is NOT defined there
    Import("env")                      # noqa: F821
    root = env.subst("$PROJECT_DIR")   # noqa: F821
except NameError:                      # plain `python3 tools/embed_web.py`
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

files = [("index.html", "kIndexGz"), ("style.css", "kStyleGz"), ("app.js", "kAppGz")]
out = ["// GENERATED by tools/embed_web.py from /data - do not edit.", "#pragma once", "#include <stdint.h>", "#include <stddef.h>", ""]
for name, sym in files:
    raw = open(os.path.join(root, "data", name), "rb").read()
    gz = gzip.compress(raw, 9, mtime=0)
    out.append("// %s: %d -> %d bytes gzip" % (name, len(raw), len(gz)))
    out.append("static const uint8_t %s[] = {" % sym)
    for i in range(0, len(gz), 16):
        out.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 16]) + ",")
    out.append("};")
    out.append("static const size_t %sLen = sizeof(%s);\n" % (sym, sym))
path = os.path.join(root, "src", "WebAssets.h")
new = "\n".join(out)
if not os.path.exists(path) or open(path).read() != new:
    open(path, "w").write(new)
    print("WebAssets.h regenerated")
